def generate_evaluation_corpus(n_samples: int = 120) -> List[Dict[str, Any]]:
    """
    Constructs a controlled, reproducible evaluation corpus representing:
    - 40 Authentic news-style photos (natural 1/f spectral decay, uniform sensor noise)
    - 30 Manipulated / spliced photos (localized foreign patches, boundary gradient discrepancies)
    - 25 AI-generated images from known generator distribution (diffusion upsampling grid artifacts)
    - 25 AI-generated images from held-out / unseen generator distribution
    """
    corpus = []
    np.random.seed(42)

    # 1. Authentic News Photos
    for i in range(40):
        # Generate varied natural-spectrum imagery
        x = np.linspace(0, 15, 256)
        y = np.linspace(0, 15, 256)
        xx, yy = np.meshgrid(x, y)
        texture = np.sin(xx / (1.5 + (i % 3))) + np.cos(yy / (2.0 + (i % 4)))
        noise = np.random.normal(120, 12, (256, 256))
        raw = np.clip((texture * 30 + noise), 0, 255).astype(np.uint8)
        img = Image.fromarray(np.dstack([raw, raw, raw]))
        corpus.append({
            "id": f"auth_{i:03d}",
            "image": img,
            "category": "authentic",
            "is_manipulated": 0,
            "is_synthetic": 0,
            "is_unseen_gen": False
        })

    # 2. Manipulated / Spliced Photos
    for i in range(30):
        base_noise = np.random.normal(130, 15, (256, 256))
        raw = np.clip(base_noise, 0, 255).astype(np.uint8)
        img = Image.fromarray(np.dstack([raw, raw, raw]))
        
        # Paste foreign inconsistent patch
        patch_noise = np.random.normal(210, 45, (80, 80))
        patch_raw = np.clip(patch_noise, 0, 255).astype(np.uint8)
        patch_img = Image.fromarray(np.dstack([patch_raw, patch_raw, patch_raw]))
        img.paste(patch_img, (60 + (i % 80), 70 + (i % 80)))
        
        corpus.append({
            "id": f"manip_{i:03d}",
            "image": img,
            "category": "manipulated",
            "is_manipulated": 1,
            "is_synthetic": 0,
            "is_unseen_gen": False
        })

    # 3. AI-Generated Photos (Known Generators: Diffusion)
    for i in range(25):
        y, x = np.ogrid[:256, :256]
        # Periodic checkerboard upsampling artifact
        checker = np.sin(x * np.pi / 2.0) * np.sin(y * np.pi / 2.0)
        noise = np.random.normal(128, 10, (256, 256))
        combined = np.clip(noise + checker * 45.0, 0, 255).astype(np.uint8)
        img = Image.fromarray(np.dstack([combined, combined, combined]))
        corpus.append({
            "id": f"ai_known_{i:03d}",
            "image": img,
            "category": "ai_known",
            "is_manipulated": 0,
            "is_synthetic": 1,
            "is_unseen_gen": False
        })

    # 4. AI-Generated Photos (Held-Out / Unseen Generators)
    for i in range(25):
        y, x = np.ogrid[:256, :256]
        # Diagonal / subtle non-standard frequency lattice
        lattice = np.sin((x + y) * np.pi / 2.8) * 35.0
        noise = np.random.normal(135, 14, (256, 256))
        combined = np.clip(noise + lattice, 0, 255).astype(np.uint8)
        img = Image.fromarray(np.dstack([combined, combined, combined]))
        corpus.append({
            "id": f"ai_unseen_{i:03d}",
            "image": img,
            "category": "ai_unseen",
            "is_manipulated": 0,
            "is_synthetic": 1,
            "is_unseen_gen": True
        })

    return corpus

